/**
 * ExportView.js
 * MVC - View Layer: Exporting Marksheets to PDF, Excel (.xlsx), and Direct Print.
 */

class ExportView {
    constructor() {}

    /**
     * Generate and download professional PDF marksheet
     */
    exportPDF(cls, activeTab = 'all') {
        const { jsPDF } = window.jspdf || {};
        if (!jsPDF) {
            alert('PDF ലൈബ്രറി ലോഡ് ചെയ്യാൻ കഴിഞ്ഞില്ല. ദയവായി പേജ് റീഫ്രഷ് ചെയ്യുക അല്ലെങ്കിൽ പ്രിന്റ് ഓപ്ഷൻ ഉപയോഗിക്കുക.');
            window.print();
            return;
        }

        const doc = new jsPDF({
            orientation: 'landscape',
            unit: 'mm',
            format: 'a4'
        });

        const topics = cls.topics || [];
        const stats = window.marksheetModel.calculateStats(cls);

        let sheetTitle = 'എല്ലാ വിദ്യാർത്ഥികളുടെയും മാർക്ക്ഷീറ്റ് (All Students)';
        let results = stats.allResults;

        if (activeTab === 'boys') {
            sheetTitle = 'ആൺകുട്ടികളുടെ മാർക്ക്ഷീറ്റ് (Boys Marksheet)';
            results = stats.boysResults;
        } else if (activeTab === 'girls') {
            sheetTitle = 'പെൺകുട്ടികളുടെ മാർക്ക്ഷീറ്റ് (Girls Marksheet)';
            results = stats.girlsResults;
        }

        // Header Styling
        doc.setFont('helvetica', 'bold');
        doc.setFontSize(18);
        doc.setTextColor(24, 43, 73);
        doc.text(cls.madrasaName || 'MADRASA / SCHOOL', 148, 16, { align: 'center' });

        doc.setFontSize(13);
        doc.setFont('helvetica', 'normal');
        doc.setTextColor(55, 65, 81);
        doc.text(`${cls.className}  •  ${cls.examName}  (${cls.academicYear || ''})`, 148, 23, { align: 'center' });

        doc.setFontSize(11);
        doc.setFont('helvetica', 'bold');
        doc.setTextColor(79, 70, 229);
        doc.text(sheetTitle, 148, 29, { align: 'center' });

        // Line separator
        doc.setDrawColor(203, 213, 225);
        doc.setLineWidth(0.5);
        doc.line(14, 32, 283, 32);

        // Prepare Table Columns & Rows
        const head = [
            [
                'Roll',
                'Student Name',
                ...topics.map(t => `${t.name}\n(Max: ${t.maxMarks})`),
                'Total',
                '%',
                'Grade',
                'Rank',
                'Status'
            ]
        ];

        const body = results.map(res => {
            const markCells = topics.map(t => {
                const s = res.topicScores[t.id];
                if (!s || s.isEmpty) return '-';
                if (s.isAbsent) return 'Ab';
                return s.numeric.toString();
            });

            return [
                res.student.rollNo || '-',
                res.student.name,
                ...markCells,
                `${res.totalScored} / ${res.totalMax}`,
                `${res.percentage}%`,
                res.grade,
                res.rank,
                res.status
            ];
        });

        // Generate AutoTable
        doc.autoTable({
            head: head,
            body: body,
            startY: 35,
            theme: 'grid',
            headStyles: {
                fillColor: [30, 41, 59],
                textColor: [255, 255, 255],
                fontStyle: 'bold',
                halign: 'center',
                valign: 'middle',
                fontSize: 9
            },
            bodyStyles: {
                fontSize: 9,
                valign: 'middle',
                halign: 'center'
            },
            columnStyles: {
                0: { cellWidth: 15 },
                1: { cellWidth: 50, halign: 'left' }
            },
            alternateRowStyles: {
                fillColor: [248, 250, 252]
            },
            margin: { left: 14, right: 14, bottom: 25 },
            didDrawPage: function (data) {
                // Footer
                const pageHeight = doc.internal.pageSize.height || 210;
                doc.setFontSize(8);
                doc.setFont('helvetica', 'normal');
                doc.setTextColor(148, 163, 184);
                doc.text(
                    `Generated by Marksheet Helper  •  Date: ${new Date().toLocaleDateString()}`,
                    14,
                    pageHeight - 8
                );
            }
        });

        // Signatures block on final page
        const finalY = doc.lastAutoTable.finalY + 15;
        const pageHeight = doc.internal.pageSize.height || 210;

        if (finalY < pageHeight - 25) {
            doc.setFontSize(9);
            doc.setFont('helvetica', 'normal');
            doc.setTextColor(30, 41, 59);

            // Left: Class Teacher signature
            doc.line(20, finalY + 10, 80, finalY + 10);
            doc.text("Class Teacher's Signature", 30, finalY + 15);

            // Right: Headmaster / Principal signature
            doc.line(215, finalY + 10, 275, finalY + 10);
            doc.text("Headmaster / Principal", 225, finalY + 15);
        }

        // Clean filename
        const safeOrg = (cls.madrasaName || 'Marksheet').replace(/[^a-zA-Z0-9]/g, '_');
        const safeClass = (cls.className || 'Class').replace(/[^a-zA-Z0-9]/g, '_');
        doc.save(`${safeOrg}_${safeClass}_${activeTab}_marksheet.pdf`);
    }

    /**
     * Generate and download Excel spreadsheet (.xlsx)
     */
    exportExcel(cls, activeTab = 'all') {
        const XLSX = window.XLSX;
        if (!XLSX) {
            alert('Excel ലൈബ്രറി ലോഡ് ചെയ്യാൻ കഴിഞ്ഞില്ല. ദയവായി പേജ് റീഫ്രഷ് ചെയ്യുക.');
            return;
        }

        const stats = window.marksheetModel.calculateStats(cls);
        const topics = cls.topics || [];

        let results = stats.allResults;
        let sheetName = 'All Students';

        if (activeTab === 'boys') {
            results = stats.boysResults;
            sheetName = 'Boys';
        } else if (activeTab === 'girls') {
            results = stats.girlsResults;
            sheetName = 'Girls';
        }

        const rows = [];

        // Meta info header rows
        rows.push([cls.madrasaName || 'Marksheet Helper']);
        rows.push([`Class: ${cls.className}`, `Exam: ${cls.examName}`, `Year: ${cls.academicYear || ''}`]);
        rows.push([`Sheet: ${sheetName}`, `Exported on: ${new Date().toLocaleString()}`]);
        rows.push([]); // blank row

        // Column Headers
        const headerRow = [
            'Roll No',
            'Student Name',
            'Gender',
            ...topics.map(t => `${t.name} (Max: ${t.maxMarks})`),
            'Total Scored',
            'Max Marks',
            'Percentage (%)',
            'Grade',
            'Rank',
            'Status'
        ];
        rows.push(headerRow);

        // Data Rows
        results.forEach(res => {
            const topicMarks = topics.map(t => {
                const s = res.topicScores[t.id];
                if (!s || s.isEmpty) return '';
                if (s.isAbsent) return 'Ab';
                return s.numeric;
            });

            rows.push([
                res.student.rollNo || '',
                res.student.name,
                res.student.gender === 'boy' ? 'Boy' : 'Girl',
                ...topicMarks,
                res.totalScored,
                res.totalMax,
                res.percentage,
                res.grade,
                res.rank,
                res.status
            ]);
        });

        const wb = XLSX.utils.book_new();
        const ws = XLSX.utils.aoa_to_sheet(rows);

        XLSX.utils.book_append_sheet(wb, ws, sheetName);

        const safeOrg = (cls.madrasaName || 'Marksheet').replace(/[^a-zA-Z0-9]/g, '_');
        const safeClass = (cls.className || 'Class').replace(/[^a-zA-Z0-9]/g, '_');
        XLSX.writeFile(wb, `${safeOrg}_${safeClass}_${activeTab}.xlsx`);
    }

    /**
     * Trigger direct browser printing
     */
    triggerPrint() {
        window.print();
    }
}

window.exportView = new ExportView();
