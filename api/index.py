import os
import json
import urllib.request
import urllib.error
from flask import Flask, jsonify, request

app = Flask(__name__)

@app.route('/api/status')
def status():
    return jsonify({
        'status': 'online',
        'application': 'Marksheet Helper',
        'architecture': 'MVC (Model-View-Controller)',
        'storage': 'Isolated LocalStorage Vault',
        'ai_scanner': 'Gemini 1.5 Flash',
        'version': '1.1.0'
    })

@app.route('/api/gemini-extract', methods=['POST'])
def gemini_extract():
    """
    Extracts student names, roll numbers, and marks from a marksheet photo
    using Google's Gemini 1.5 Flash multimodal AI model.
    """
    try:
        data = request.get_json(force=True, silent=True) or {}
        image_b64 = data.get('image')
        mime_type = data.get('mimeType', 'image/jpeg')
        api_key = data.get('apiKey') or request.headers.get('X-Gemini-Key') or os.environ.get('GEMINI_API_KEY')

        if not api_key:
            return jsonify({
                'success': False,
                'error': 'Gemini API Key missing. Please provide your Google AI Studio API key.'
            }), 400

        if not image_b64:
            return jsonify({
                'success': False,
                'error': 'No image provided for extraction.'
            }), 400

        # Strip data URL prefix if present
        if ',' in image_b64:
            image_b64 = image_b64.split(',', 1)[1]

        prompt = (
            "You are an expert OCR and marksheet parser for madrasas and schools. "
            "Analyze this marksheet / student list image carefully. "
            "Extract all students and their subject marks into a JSON array with this exact format:\n"
            "[\n"
            "  {\n"
            "    \"rollNo\": \"1\",\n"
            "    \"name\": \"Student Name (in Malayalam or English as written)\",\n"
            "    \"gender\": \"boy\" or \"girl\",\n"
            "    \"marks\": {\n"
            "      \"Subject1\": 45,\n"
            "      \"Subject2\": 38\n"
            "    }\n"
            "  }\n"
            "]\n"
            "If only student names or attendance are listed without marks, extract rollNo, name, and empty marks {}. "
            "If subject names are in Malayalam (e.g. ഖുർആൻ, ഫിഖ്ഹ്, അഖീദ, താരീഖ്, അഖ്‌ലാഖ്, തജ്‌വീദ്, ലിസാൻ), preserve them accurately. "
            "Return ONLY the valid JSON array. Do not include markdown code block backticks."
        )

        gemini_url = f"https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key={api_key}"
        payload = {
            "contents": [
                {
                    "parts": [
                        {"text": prompt},
                        {
                            "inline_data": {
                                "mime_type": mime_type,
                                "data": image_b64
                            }
                        }
                    ]
                }
            ],
            "generationConfig": {
                "temperature": 0.1,
                "response_mime_type": "application/json"
            }
        }

        req = urllib.request.Request(
            gemini_url,
            data=json.dumps(payload).encode('utf-8'),
            headers={'Content-Type': 'application/json'}
        )

        with urllib.request.urlopen(req, timeout=30) as response:
            res_data = json.loads(response.read().decode('utf-8'))

        candidates = res_data.get('candidates', [])
        if not candidates:
            return jsonify({'success': False, 'error': 'No output generated by Gemini AI.'}), 500

        text_content = candidates[0].get('content', {}).get('parts', [{}])[0].get('text', '').strip()

        # Remove markdown blocks if Gemini wrapped it in ```json ... ```
        if text_content.startswith('```'):
            lines = text_content.split('\n')
            if lines[0].startswith('```'):
                lines = lines[1:]
            if lines and lines[-1].startswith('```'):
                lines = lines[:-1]
            text_content = '\n'.join(lines).strip()

        parsed_students = json.loads(text_content)
        return jsonify({
            'success': True,
            'students': parsed_students
        })

    except urllib.error.HTTPError as e:
        err_msg = e.read().decode('utf-8', errors='ignore')
        return jsonify({'success': False, 'error': f'Gemini API error: {err_msg}'}), e.code
    except Exception as e:
        return jsonify({'success': False, 'error': str(e)}), 500

# Vercel WSGI entry point
handler = app
